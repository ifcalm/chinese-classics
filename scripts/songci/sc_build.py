def files():
    fs = glob.glob(os.path.join(SRC, '宋词', 'ci.song.*.json'))
    if not fs:
        sys.exit('未找到 ci.song.*.json，请设 CP_DIR')
    # ⚠ 檔名不全是數字：這份數據裏還有 ci.song.2019y.json（增補檔），
    # 直接 int() 會炸。站內既有詞集的首數（蘇軾 362、辛棄疾 629）正是含它的結果。
    def key(x):
        t = os.path.basename(x).split('.')[2]
        return (0, int(t)) if t.isdigit() else (1, 0)
    return sorted(fs, key=key)


