def title_of(p):
    """题名體例照站內既有詞集：词牌·首句前七字（源多無 title 欄，只有 rhythmic）。"""
    # 词牌名裏混着 ・(U+30FB)，站內一律用 ·——同 2026-08-20 的全站歸一
    r = (p.get('rhythmic') or p.get('title') or '').strip().replace('・', '·').replace('•', '·')
    head = ''.join(HAN.findall(''.join(p.get('paragraphs', []))))[:7]
    return (r + '·' + head) if r and head else (r or head or '无题')


def main():
    want = {a for a, _, _ in BOOKS}
    data = collections.defaultdict(list)
    for f in files():
        for p in json.load(open(f, encoding='utf-8')):
            a = (p.get('author') or '').strip()
            if a in want:
                data[a].append(p)

    os.makedirs(DEST, exist_ok=True)
    open(os.path.join(DEST, '_index.md'), 'w', encoding='utf-8').write(
        '---\ntitle: "宋词诸家"\nweight: 32\n'
        'summary: "《全宋词》所收、站内尚无别集的两宋词人，据 chinese-poetry 辑录。"\n---\n')

    rows = []
    for w, (au, title, summ) in enumerate(BOOKS, 1):
        slug = SLUG[au]
        d = os.path.join(DEST, slug)
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, '_index.md'), 'w', encoding='utf-8').write(
            '---\ntitle: "%s"\nweight: %d\nkind: "book"\nauthor: "%s"\ndynasty: "宋"\n'
            'summary: "%s"\n---\n' % (title, w, '佚名' if au == '无名氏' else au, summ))
        n = ch = odd = simp = 0
        for p in data[au]:
            body = '\n\n'.join(x.strip().replace('・', '·').replace('•', '·')
                                for x in p.get('paragraphs', []) if x.strip())
            if not body:
                continue
            n += 1
            ch += len(HAN.findall(body))
            odd += len(ODD.findall(body))
            simp += sum(body.count(c) for c in SIMP)
            open(os.path.join(d, '%04d.md' % n), 'w', encoding='utf-8').write(
                '---\ntitle: "%s"\nweight: %d\n---\n\n%s\n'
                % (title_of(p).replace('"', '”'), n, body))
        rows.append((title, au, n, ch, odd))
    print('%-16s %-6s %6s %8s %5s' % ('书', '词人', '首', '汉字', '缺字'))
    for t, a, n, c, o in rows:
        print('%-16s %-6s %6d %8d %5d' % (t, a, n, c, o))
    print('合计 %d 部 · %d 首 · %d 汉字' % (len(rows), sum(r[2] for r in rows),
                                          sum(r[3] for r in rows)))


if __name__ == '__main__':
    main()
